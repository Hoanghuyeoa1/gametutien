/** Tính thời gian du hành giữa 2 node (ms) dựa vào khoảng cách SVG và tốc độ tàu */
export function calcTravelTimeMs(fromNode: CosmicNode, toNode: CosmicNode, vesselSpeed: number): number {
  const dx = toNode.x - fromNode.x;
  const dy = toNode.y - fromNode.y;
  const dist = Math.sqrt(dx * dx + dy * dy); // 0-141 (theo %)
  const normalized = dist / 30; // Chuẩn hóa: 30 đơn vị ≈ 1 khoảng cách bình thường
  return Math.round((BASE_TRAVEL_TIME_MS / vesselSpeed) * normalized * 1000) / 1000;
}
